"""Warning alert engine for generating and managing safeguarded geohazard advisories."""

from datetime import datetime, timezone, timedelta
from typing import Dict, List, Optional, Tuple, Any
from sqlalchemy.orm import Session

from app.models.alert import Alert
from app.services.susceptibility.base import ExplainableAssessmentResult, utc_now
from app.services.alerts.safeguards import AlertSafeguards


class AlertWarningEngine:
    """Evaluates risk assessment triggers and manages early warning advisories with strict safety invariants."""

    def __init__(self, cooldown_hours: float = 6.0):
        self.cooldown_hours = cooldown_hours

    def evaluate_and_dispatch(
        self,
        db: Session,
        assessment: ExplainableAssessmentResult,
        triggering_assessment_id: Optional[int] = None,
    ) -> Tuple[Optional[Alert], Optional[str]]:
        """
        Evaluates an assessment and issues a safeguarded advisory if thresholds are breached and safeguards pass.
        Returns (Alert, None) on success or (None, reason) if suppressed.
        """
        can_issue, reason = AlertSafeguards.can_issue_alert(
            db, assessment, cooldown_hours=self.cooldown_hours
        )
        if not can_issue:
            return None, reason

        now = utc_now()
        cooldown_until = now + timedelta(hours=self.cooldown_hours)
        fingerprint = AlertSafeguards.generate_fingerprint(
            assessment.location_id, assessment.risk_category, now
        )

        # Title formatting with mandatory experimental/demo separation
        prefix = "[DEMONSTRATION ALERT]" if assessment.is_demo else "[EXPERIMENTAL EARLY WARNING]"
        title = f"{prefix} {assessment.risk_category.upper()}: Slope Stability Warning at {assessment.location_name}"

        # Uncertainty and limitations notes
        uncertainty_notes = (
            "SAFETY DISCLAIMER: This is an experimental algorithmic warning generated by LandslideGuard AI. "
            "It must NOT be treated as an official statutory evacuation order. "
            "Official emergency management decisions must rely on authorized advisories from NDMA/SDMA. "
        )
        if assessment.limitations:
            uncertainty_notes += "Identified Data Limitations: " + " | ".join(assessment.limitations)

        # Description synthesizing rationale and contributing factors
        factors_summary = ", ".join(
            f"{f.factor_name}: {f.raw_value} {f.unit} ({f.percentage_of_total}%)"
            for f in assessment.contributing_factors[:3]
        )
        description = (
            f"Automated hazard assessment detected {assessment.risk_category.upper()} failure probability "
            f"(Score: {assessment.risk_score:.2f}). "
            f"Contributing factors: {factors_summary}. "
            f"Rationale: {assessment.analytical_rationale}"
        )

        source = (
            "[DEMO] LandslideGuard Safeguard Engine"
            if assessment.is_demo
            else "LandslideGuard AI Safeguard Engine (Experimental Prototype)"
        )

        kwargs = {
            "location_id": assessment.location_id,
            "severity": assessment.risk_category,
            "title": title[:150],
            "description": description,
            "status": "issued",
            "source": source,
            "created_at": now,
        }

        # Optional schema fields
        if hasattr(Alert, "triggering_assessment_id"):
            kwargs["triggering_assessment_id"] = triggering_assessment_id
        if hasattr(Alert, "alert_fingerprint"):
            kwargs["alert_fingerprint"] = fingerprint
        if hasattr(Alert, "cooldown_until"):
            kwargs["cooldown_until"] = cooldown_until
        if hasattr(Alert, "uncertainty_notes"):
            kwargs["uncertainty_notes"] = uncertainty_notes
        if hasattr(Alert, "is_experimental"):
            kwargs["is_experimental"] = True

        alert = Alert(**kwargs)
        db.add(alert)
        db.flush()

        return alert, None

    def acknowledge_alert(self, db: Session, alert_id: int) -> Alert:
        """Transitions alert to acknowledged state."""
        alert = db.query(Alert).filter(Alert.id == alert_id).first()
        if not alert:
            raise ValueError(f"Alert with ID {alert_id} not found.")

        alert.status = "acknowledged"
        alert.acknowledged_at = utc_now()
        db.flush()
        return alert

    def resolve_alert(self, db: Session, alert_id: int) -> Alert:
        """Transitions alert to resolved state."""
        alert = db.query(Alert).filter(Alert.id == alert_id).first()
        if not alert:
            raise ValueError(f"Alert with ID {alert_id} not found.")

        alert.status = "resolved"
        db.flush()
        return alert
